// Regenerates the table of contents in README.md from .vitepress/toc.mjs.
// `--check` exits with 1 if README.md is out of date (used in CI).

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { sections, root, topicPath, isWritten } from '../.vitepress/toc.mjs'

const START = '<!-- toc:start -->'
const END = '<!-- toc:end -->'
const readmePath = resolve(root, 'README.md')

const total = sections.reduce((sum, s) => sum + s.topics.length, 0)
const written = sections.reduce((sum, s) => sum + s.topics.filter((t) => isWritten(s, t)).length, 0)

const toc = [
  START,
  '<!-- Generated by `npm run readme` from .vitepress/toc.mjs — do not edit by hand. -->',
  '',
  `Написано тем: ${written} из ${total}. Темы без ✅ ещё не написаны.`,
  '',
  ...sections.flatMap((section, i) => [
    `### ${i + 1}. ${section.title}${section.level === 'дополнительно' ? ' · дополнительно' : ''}`,
    '',
    ...section.topics.map((topic, j) => {
      const mark = isWritten(section, topic) ? ' ✅' : ''
      return `${j + 1}. [${topic.title}](${topicPath(section, topic)})${mark}`
    }),
    '',
  ]),
  END,
].join('\n')

const current = readFileSync(readmePath, 'utf8')
const pattern = new RegExp(`${START}[\\s\\S]*?${END}`)
if (!pattern.test(current)) {
  console.error(`README.md has no ${START} … ${END} block`)
  process.exit(1)
}
const next = current.replace(pattern, toc)

if (process.argv.includes('--check')) {
  if (next !== current) {
    console.error('README.md is out of date: run `npm run readme` and commit the result')
    process.exit(1)
  }
  console.log('README.md is up to date')
} else {
  writeFileSync(readmePath, next)
  console.log(`README.md updated: ${written}/${total} topics written`)
}
